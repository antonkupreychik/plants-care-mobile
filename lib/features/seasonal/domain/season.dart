/// Сезон года для экрана 35 «Сезонные интервалы».
///
/// Backend моделирует сезонность двумя интервалами (лето/зима, см.
/// `SeasonalScheduleDto.summerIntervalDays`/`winterIntervalDays`), но для UI
/// дизайн показывает все четыре сезона. Этот enum — клиентская презентационная
/// классификация текущего месяца, НЕ источник интервалов: реальные интервалы
/// считает backend per-plant. Здесь только «какой сейчас сезон» для подсветки.
enum Season {
  spring,
  summer,
  autumn,
  winter;

  /// Полугодие, к которому относится сезон в модели backend (лето/зима).
  /// Весна тяготеет к лету (растения просыпаются, пьют чаще), осень — к зиме
  /// (замедляются). Используется, чтобы привязать сезон к
  /// `summerIntervalDays`/`winterIntervalDays`, если они доступны.
  bool get isWarmHalf => this == Season.spring || this == Season.summer;

  /// Сезон по номеру месяца (1..12) для северного полушария. Декабрь–февраль —
  /// зима, март–май — весна, июнь–август — лето, сентябрь–ноябрь — осень.
  /// Вне диапазона (страховка) → [Season.summer] (нейтральный дефолт).
  static Season ofMonth(int month) => switch (month) {
        12 || 1 || 2 => Season.winter,
        3 || 4 || 5 => Season.spring,
        6 || 7 || 8 => Season.summer,
        9 || 10 || 11 => Season.autumn,
        _ => Season.summer,
      };
}
