/// Сторона света, куда выходит окно рядом с растением (шаг 04c).
///
/// Чистый Dart, без Flutter. Влияет на освещённость и, в перспективе, на
/// рекомендации ухода. На текущем backend поля для стороны окна нет
/// (`POST /plants` принимает только `{name, locationId, speciesId, notes}`),
/// поэтому выбор пока **UI-only**: хранится в черновике для будущего использования
/// и не уходит в запрос. Когда backend добавит поле — маппинг подключается здесь.
enum WindowSide {
  /// Юг — много солнца.
  south,

  /// Восток — мягкое утро.
  east,

  /// Запад — тёплый вечер.
  west,

  /// Север — мало света.
  north,
}
