/// Контракт нативного социального входа (Google / Apple) для data-слоя.
///
/// Абстракция отделяет [AuthRepository] от конкретных SDK (google_sign_in,
/// sign_in_with_apple): репозиторий зависит только от этого интерфейса, что
/// держит data-слой тестируемым (MADR-002) и позволяет подменить шлюз в тестах.
///
/// Контракт каждого метода:
/// - возвращает токен провайдера (Google OIDC `id_token` / Apple `identityToken`)
///   для обмена на пару JWT через backend;
/// - возвращает `null`, если **пользователь отменил** вход (отмена — не ошибка,
///   UI не должен показывать сообщение);
/// - **бросает** исключение при реальной ошибке SDK (нет конфигурации, сбой
///   платформы, провайдер вернул пустой токен) — репозиторий завернёт его в
///   [SocialAuthFailure].
abstract interface class SocialSignIn {
  /// Интерактивный вход через Google. `null` — пользователь отменил.
  /// Бросает при ошибке SDK/конфигурации.
  Future<String?> googleIdToken();

  /// Интерактивный вход через Apple (iOS). `null` — пользователь отменил.
  /// Бросает при ошибке SDK/конфигурации.
  Future<String?> appleIdentityToken();
}
