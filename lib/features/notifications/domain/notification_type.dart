/// Тип уведомления в ленте (`GET /api/v1/notifications`,
/// `NotificationDto.type`).
///
/// Backend отдаёт строковый enum `care` / `alert` / `award` / `report` /
/// `system` (`NotificationDtoType`). Это domain-проекция: маппинг 1:1 делает
/// маппер data-слоя (MADR-002), нераспознанный код схлопывается в [system]
/// (нейтральный fallback — не падаем, см. `NotificationDtoMapper`).
///
/// UI выбирает иконку/акцент по типу; тексты («голосом растения») приходят с
/// backend в `title`/`body` — клиент их не генерирует.
enum NotificationType {
  /// Напоминание/событие ухода за растением.
  care,

  /// Тревога: растению нужна срочная помощь.
  alert,

  /// Награда/достижение (стрик, бейдж).
  award,

  /// Периодический отчёт (например, недельный).
  report,

  /// Системное уведомление + безопасный fallback для нераспознанного типа.
  system,
}
