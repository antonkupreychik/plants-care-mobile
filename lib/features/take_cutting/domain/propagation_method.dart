/// Способ размножения черенка (экран 18).
///
/// UI-only выбор: backend `PlantCreateRequest` сейчас не принимает тип
/// размножения отдельным полем, поэтому при создании ростка он не уходит на
/// сервер (см. [TakeCuttingRepository.createCutting]). Хранится в состоянии
/// мастера для подсветки активной карточки и (в будущем) для записи как
/// `PlantEvent` типа `CUTTING` — отдельная задача (issue #63).
enum PropagationMethod {
  /// «В воду» (💧, ~3 недели).
  water,

  /// «В грунт» (🪴, ~5 недель).
  soil,

  /// «Мох» (🌿, долго).
  moss,
}
